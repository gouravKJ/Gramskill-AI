import type { Job, JobSkill, SkillImportance, EducationLevel, ExperienceLevel, JobType, WorkMode, OpportunitySource } from "@/types";

/**
 * DEMO job dataset.
 *
 * Every employer, salary and location here is fictional and exists only to
 * exercise the matching engine, the agent tools and the analytics views.
 * The UI marks all of this data as "Demo" and the seed script writes it into
 * PostgreSQL so a real deployment can be swapped in without code changes.
 */

interface JobSeed {
  id: string;
  title: string;
  company: string;
  companyType: Job["companyType"];
  sector: string;
  source: OpportunitySource;
  locationId: string;
  workMode: WorkMode;
  jobType: JobType;
  salaryMin: number | null;
  salaryMax: number | null;
  experienceRequired: ExperienceLevel;
  educationRequired: EducationLevel;
  description: string;
  requirements: string[];
  responsibilities: string[];
  skills: [string, SkillImportance][];
  daysAgo: number;
  deadlineInDays: number;
  openings?: number;
  ruralFriendly?: boolean;
  localLanguage?: boolean;
}

function buildJob(seed: JobSeed): Job {
  const skills: JobSkill[] = seed.skills.map(([skillId, importance]) => ({
    skillId,
    importance,
    minProficiency: importance === "REQUIRED" ? "INTERMEDIATE" : "BEGINNER",
  }));

  return {
    id: seed.id,
    title: seed.title,
    company: seed.company,
    companyType: seed.companyType,
    sector: seed.sector,
    source: seed.source,
    description: seed.description,
    requirements: seed.requirements,
    responsibilities: seed.responsibilities,
    locationId: seed.locationId,
    workMode: seed.workMode,
    jobType: seed.jobType,
    salaryMin: seed.salaryMin,
    salaryMax: seed.salaryMax,
    experienceRequired: seed.experienceRequired,
    educationRequired: seed.educationRequired,
    openings: seed.openings ?? 1,
    postedAt: isoDaysFromNow(-seed.daysAgo),
    deadline: isoDaysFromNow(seed.deadlineInDays),
    isRuralFriendly: seed.ruralFriendly ?? true,
    localLanguageSupport: seed.localLanguage ?? true,
    skills,
    contactEmail: `careers@${seed.company.toLowerCase().replace(/[^a-z0-9]+/g, "")}.demo`,
  };
}

function isoDaysFromNow(days: number) {
  const d = new Date();
  d.setHours(9, 30, 0, 0);
  d.setDate(d.getDate() + days);
  return d.toISOString();
}

